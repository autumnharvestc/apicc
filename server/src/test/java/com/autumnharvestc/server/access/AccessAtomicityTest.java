    @ParameterizedTest
    @ValueSource(strings={"member-put","member-delete","acl-put","acl-delete","ws-caps","project-caps","ws-policy","project-policy","admin-role","admin-disable","admin-enable"})
    void auditFailureRollsBackEveryAccessMutation(String kind) throws Exception {
        Scope f = scope(); member(f,"EDITOR",0).andExpect(status().isOk());
        if(kind.equals("member-delete"))mvc.perform(put(f.projectUrl()+"/access-members/"+f.target().id()).header("Authorization","Bearer "+f.owner().token()).contentType("application/json")
                .content("{\"expectedRevision\":0,\"capabilities\":{\"publication.manage\":\"allow\",\"script.edit\":\"deny\"}}")).andExpect(status().isOk());
        if(kind.equals("acl-delete")) acl(f,"NONE",0).andExpect(status().isOk());
        if(kind.startsWith("admin-")) jdbc.update("UPDATE users SET role='SUPERADMIN' WHERE id=?",Long.valueOf(f.owner().id()));
        if(kind.equals("admin-enable")) users.setDisabled(Long.valueOf(f.target().id()),true);
        var before = access.resolve(Long.valueOf(f.target().id()),Long.valueOf(f.workspace()),Long.valueOf(f.project()));
        String constraint = "audit_block_"+f.workspace();
        // Setup writes now produce real audit. Clear only this synthetic actor's setup rows before installing the fault.
        jdbc.update("DELETE FROM access_audit WHERE actor_id=?",Long.valueOf(f.owner().id()));
        jdbc.execute("ALTER TABLE access_audit ADD CONSTRAINT "+constraint+" CHECK(actor_id<>"+f.owner().id()+")");
        try {
            var result = switch(kind) {
                case "member-put" -> member(f,"VIEWER",1);
                case "member-delete" -> mvc.perform(delete(f.workspaceUrl()+"/members/"+f.target().id()).param("expectedRevision","1").header("Authorization","Bearer "+f.owner().token()));
                case "acl-put" -> acl(f,"VIEWER",0);
                case "acl-delete" -> mvc.perform(delete(f.projectUrl()+"/acl").param("userId",f.target().id()).param("expectedRevision","1").header("Authorization","Bearer "+f.owner().token()));
                case "admin-role" -> mvc.perform(put("/api/v1/admin/users/"+f.target().id()+"/workspace-role").header("Authorization","Bearer "+f.owner().token()).contentType("application/json")
                        .content(json.writeValueAsString(Map.of("workspaceId",f.workspace(),"role","VIEWER","expectedRevision",1))));
                case "admin-disable", "admin-enable" -> mvc.perform(post("/api/v1/admin/users/"+f.target().id()+"/"+kind.substring(6)).header("Authorization","Bearer "+f.owner().token())
                        .contentType("application/json").content("{\"expectedRevision\":1}"));
                default -> {
                    boolean project=kind.startsWith("project"); boolean policy=kind.endsWith("policy");
                    String url=(project?f.projectUrl():f.workspaceUrl())+(policy?"/access-policy":"/access-members/"+f.target().id());
                    yield mvc.perform(put(url).header("Authorization","Bearer "+f.owner().token()).contentType("application/json")
                            .content(json.writeValueAsString(Map.of("expectedRevision",policy||project?0:1,policy?"defaults":"capabilities",Map.of("task.execute","deny")))));
                }
            };
            var after=access.resolve(Long.valueOf(f.target().id()),Long.valueOf(f.workspace()),Long.valueOf(f.project()));
            assertAll(
                    () -> result.andExpect(status().isInternalServerError()),
                    () -> assertThat(memberships.findRole(Long.valueOf(f.workspace()),Long.valueOf(f.target().id()))).contains(Role.EDITOR),
                    () -> assertThat(after).isEqualTo(before));
            if(kind.equals("admin-disable"))mvc.perform(get("/api/v1/me").header("Authorization","Bearer "+f.target().token())).andExpect(status().isOk());
            if(kind.equals("member-delete"))assertAll(
                    ()->assertThat(jdbc.queryForObject("SELECT revision FROM project_acl WHERE workspace_id=? AND project_id=? AND user_id=?",Long.class,Long.valueOf(f.workspace()),Long.valueOf(f.project()),Long.valueOf(f.target().id()))).isEqualTo(1L),
                    ()->assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM access_member_capabilities WHERE workspace_id=? AND project_id=? AND user_id=? AND mode IN ('allow','deny')",Integer.class,Long.valueOf(f.workspace()),Long.valueOf(f.project()),Long.valueOf(f.target().id()))).isEqualTo(2));
        } finally { jdbc.execute("ALTER TABLE access_audit DROP CONSTRAINT "+constraint); }
    }

