    @ParameterizedTest @ValueSource(strings={"disabled","demoted"})
    void realLockWaitRechecksCurrentActorBeforeWriting(String change) throws Exception {
        Scope f=scope(); member(f,"EDITOR",0).andExpect(status().isOk());
        try(Connection gate=dataSource.getConnection();var pool=Executors.newSingleThreadExecutor()) {
            gate.setAutoCommit(false);
            try(var statement=gate.prepareStatement("SELECT revision FROM access_members WHERE workspace_id=? AND user_id=? FOR UPDATE")) {
                statement.setLong(1,Long.parseLong(f.workspace()));statement.setLong(2,Long.parseLong(f.target().id()));statement.executeQuery().close();
            }
            var write=pool.submit(()->member(f,"VIEWER",1).andReturn().getResponse().getStatus());
            long deadline=System.nanoTime()+TimeUnit.SECONDS.toNanos(5);
            boolean blocked=false;
            while(System.nanoTime()<deadline&&!write.isDone()) {
                if(jdbc.queryForObject("SELECT COUNT(*) FROM INFORMATION_SCHEMA.SESSIONS WHERE BLOCKER_ID IS NOT NULL",Integer.class)>0){blocked=true;break;}
                Thread.sleep(5);
            }
            try {
                assertThat(blocked).as("request reached a real H2 row lock, not a timing-only sleep").isTrue();
                if(change.equals("disabled"))users.setDisabled(Long.valueOf(f.owner().id()),true);
                else memberships.updateRole(Long.valueOf(f.workspace()),Long.valueOf(f.owner().id()),Role.VIEWER);
            } finally { gate.rollback(); }
            assertThat(write.get(10,TimeUnit.SECONDS)).isEqualTo(403);
            assertThat(memberships.findRole(Long.valueOf(f.workspace()),Long.valueOf(f.target().id()))).contains(Role.EDITOR);
        }
    }

