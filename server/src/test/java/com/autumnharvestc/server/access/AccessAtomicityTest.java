    @ParameterizedTest @ValueSource(strings={"acl-put","acl-delete","ws-member","ws-caps","project-caps","ws-policy","project-policy","admin-role","admin-disable","admin-enable"})
    void everyMutationAuthorityRechecksDisabledActorAfterRealLock(String kind) throws Exception {
        Scope f=scope();member(f,"EDITOR",0).andExpect(status().isOk());
        boolean project=kind.startsWith("project")||kind.startsWith("acl");
        boolean policy=kind.endsWith("policy");
        if(project&&!policy)acl(f,"EDITOR",0).andExpect(status().isOk());
        if(policy)mvc.perform(put((project?f.projectUrl():f.workspaceUrl())+"/access-policy").header("Authorization","Bearer "+f.owner().token()).contentType("application/json")
                .content("{\"expectedRevision\":0,\"defaults\":{\"task.execute\":\"allow\"}}" )).andExpect(status().isOk());
        if(kind.startsWith("admin"))jdbc.update("UPDATE users SET role='SUPERADMIN' WHERE id=?",Long.valueOf(f.owner().id()));
        if(kind.equals("admin-enable"))users.setDisabled(Long.valueOf(f.target().id()),true);
        String lock=policy?"SELECT revision FROM access_policy_scopes WHERE workspace_id=? AND project_id=? FOR UPDATE":
                project?"SELECT revision FROM project_acl WHERE workspace_id=? AND user_id=? AND project_id="+f.project()+" FOR UPDATE":
                kind.startsWith("admin-")&&!kind.equals("admin-role")?"SELECT id FROM users WHERE id=? FOR UPDATE":
                kind.equals("admin-role")?"SELECT user_id FROM memberships WHERE workspace_id=? AND user_id=? FOR UPDATE":
                "SELECT revision FROM access_members WHERE workspace_id=? AND user_id=? FOR UPDATE";
        try(Connection gate=dataSource.getConnection();var pool=Executors.newSingleThreadExecutor()){
            gate.setAutoCommit(false);
            try(var statement=gate.prepareStatement(lock)){
                if(kind.startsWith("admin-")&&!kind.equals("admin-role"))statement.setLong(1,Long.parseLong(f.target().id()));
                else{statement.setLong(1,Long.parseLong(f.workspace()));statement.setLong(2,policy?(project?Long.parseLong(f.project()):0):Long.parseLong(f.target().id()));}
                statement.executeQuery().close();
            }
            var write=pool.submit(()->{
                if(kind.equals("acl-put"))return acl(f,"VIEWER",1).andReturn().getResponse().getStatus();
                if(kind.equals("acl-delete"))return mvc.perform(delete(f.projectUrl()+"/acl").param("userId",f.target().id()).param("expectedRevision","1").header("Authorization","Bearer "+f.owner().token())).andReturn().getResponse().getStatus();
                String url,body;
                if(kind.startsWith("admin")){
                    url="/api/v1/admin/users/"+f.target().id()+"/"+(kind.equals("admin-role")?"workspace-role":kind.substring(6));
                    body=kind.equals("admin-role")?"{\"workspaceId\":\""+f.workspace()+"\",\"role\":\"VIEWER\",\"expectedRevision\":1}":"{\"expectedRevision\":1}";
                }else{
                    url=(project?f.projectUrl():f.workspaceUrl())+(policy?"/access-policy":"/access-members/"+f.target().id());
                    body=kind.equals("ws-member")?"{\"expectedRevision\":1,\"role\":\"VIEWER\"}":"{\"expectedRevision\":1,\""+(policy?"defaults":"capabilities")+"\":{\"task.execute\":\"deny\"}}";
                }
                var request=kind.equals("admin-disable")||kind.equals("admin-enable")?post(url):put(url);
                return mvc.perform(request.header("Authorization","Bearer "+f.owner().token()).contentType("application/json").content(body)).andReturn().getResponse().getStatus();
            });
            boolean blocked=false;long deadline=System.nanoTime()+TimeUnit.SECONDS.toNanos(5);
            while(System.nanoTime()<deadline&&!write.isDone()){
                if(jdbc.queryForObject("SELECT COUNT(*) FROM INFORMATION_SCHEMA.SESSIONS WHERE BLOCKER_ID IS NOT NULL",Integer.class)>0){blocked=true;break;}Thread.sleep(5);
            }
            try{assertThat(blocked).as("real H2 blocker for "+kind).isTrue();users.setDisabled(Long.valueOf(f.owner().id()),true);}
            finally{gate.rollback();}
            assertThat(write.get(10,TimeUnit.SECONDS)).isEqualTo(403);
        }
    }
